FIXTURES_DIR = pathlib.Path(__file__).parent / 'fixtures'


def make_blank_page(width=1000, height=800) -> np.ndarray:
    return np.full((height, width), 255, dtype=np.uint8)


def draw_grid(img: np.ndarray, x0, y0, w, h, rows=2, cols=2):
    cv2.rectangle(img, (x0, y0), (x0 + w, y0 + h), 0, 1)
    for i in range(1, rows):
        y = y0 + i * h // rows
        cv2.line(img, (x0, y), (x0 + w, y), 0, 1)
    for j in range(1, cols):
        x = x0 + j * w // cols
        cv2.line(img, (x, y0), (x, y0 + h), 0, 1)


class TestDetectTitleBlockCandidates:
    def test_finds_a_single_grid_region_near_the_expected_bounding_box(self):
        img = make_blank_page()
        draw_grid(img, 700, 600, 250, 150)
        candidates = detect_title_block_candidates(img, page_width=1000, page_height=800)
        assert len(candidates) == 1
        region = candidates[0]
        # Morphological detection recovers the grid's approximate extent,
        # not pixel-perfect coordinates -- a generous tolerance here checks
        # the REAL thing that matters (did it find roughly the right
        # region), not an exact pixel match that would make this test
        # brittle to kernel-size tuning.
        assert abs(region.left - 700) < 15
        assert abs(region.top - 600) < 15
        assert abs(region.width - 250) < 20
        assert abs(region.height - 150) < 20

    def test_finds_multiple_separate_grid_regions_without_merging_them(self):
        # Reproduces the real documented failure: a title block AND a
        # separate revision-history mini-table are both bordered grids:
        # must be returned as two distinct candidates, not merged into one.
        img = make_blank_page()
        draw_grid(img, 50, 50, 200, 80)       # small table, top-left
        draw_grid(img, 700, 600, 250, 150)    # title block, bottom-right
        candidates = detect_title_block_candidates(img, page_width=1000, page_height=800)
        assert len(candidates) == 2

    def test_ranks_the_region_closer_to_a_page_edge_first(self):
        img = make_blank_page(width=1200, height=1000)
        draw_grid(img, 500, 500, 150, 100)   # dead center -- far from every edge
        draw_grid(img, 20, 20, 150, 100)     # hugs the top-left corner
        candidates = detect_title_block_candidates(img, page_width=1200, page_height=1000)
        assert len(candidates) == 2
        assert candidates[0].left < candidates[1].left  # the corner one ranks first

    def test_ignores_noise_too_small_to_be_a_real_title_block(self):
        img = make_blank_page()
        cv2.rectangle(img, (100, 100), (130, 115), 0, 1)  # a tiny stray box, not a title block
        candidates = detect_title_block_candidates(img, page_width=1000, page_height=800)
        assert candidates == []

    def test_returns_no_candidates_on_a_blank_page(self):
        assert detect_title_block_candidates(make_blank_page(), 1000, 800) == []


class TestNativeTextRunsInRegion:
    def test_keeps_only_runs_fully_inside_the_region(self):
        region = GridRegion(left=100, top=100, width=200, height=100)
        inside = TextRun(text='Drawing No: S-101', left=110, top=110, width=100, height=20, conf=100.0, method='native')
        outside = TextRun(text='unrelated note', left=500, top=500, width=80, height=20, conf=100.0, method='native')
        result = native_text_runs_in_region([inside, outside], region)
        assert result == [inside]

    def test_tolerance_allows_a_run_a_few_pixels_outside_the_border(self):
        region = GridRegion(left=100, top=100, width=200, height=100)
        near_edge = TextRun(text='Rev: C', left=98, top=100, width=50, height=20, conf=100.0, method='native')
        assert native_text_runs_in_region([near_edge], region, tolerance_px=6) == [near_edge]

    def test_empty_region_input_returns_empty(self):
        region = GridRegion(left=0, top=0, width=10, height=10)
        assert native_text_runs_in_region([], region) == []


class TestPdfRectToPixelRun:
    def test_converts_pdf_point_space_to_pixel_space_at_the_given_scale(self):
        # A page 800pt tall; a rect from (left=100, bottom=700, right=200, top=720)
        # in PDF's own bottom-left-origin convention.
        run = pdf_rect_to_pixel_run('Drawing No: S-101', (100.0, 700.0, 200.0, 720.0), page_height_pt=800.0, scale=2.0)
        assert run.text == 'Drawing No: S-101'
        assert run.left == 200       # 100 * 2
        assert run.top == 160        # (800 - 720) * 2
        assert run.width == 200      # (200 - 100) * 2
        assert run.height == 40      # (720 - 700) * 2
        assert run.method == 'native'

    def test_strips_surrounding_whitespace_from_the_text(self):
        run = pdf_rect_to_pixel_run('  Rev: C  ', (0.0, 0.0, 10.0, 10.0), page_height_pt=100.0, scale=1.0)
        assert run.text == 'Rev: C'


def load_fixture_page(filename):
    pdf = pdfium.PdfDocument(str(FIXTURES_DIR / filename))
    return pdf, pdf[0]


def native_runs_for_page(page):
    textpage = page.get_textpage()
    page_width_pt, page_height_pt = page.get_size()
    scale = RASTERIZE_DPI / 72
    runs = []
    for i in range(textpage.count_rects()):
        rect = textpage.get_rect(i)
        text = textpage.get_text_bounded(*rect)
        if text.strip():
            runs.append(pdf_rect_to_pixel_run(text, rect, page_height_pt, scale))
    return runs


def gray_for_page(page):
    scale = RASTERIZE_DPI / 72
    bitmap = page.render(scale=scale)
    return render_page_to_grayscale(bitmap.to_pil())


@pytest.mark.skipif(not FIXTURES_DIR.exists(), reason="fixtures not present")
class TestEndToEndAgainstRealFixtures:
    def test_native_bottom_right_isolates_the_title_block_from_the_revision_history_table(self):
        pdf, page = load_fixture_page('native_bottom_right.pdf')
        native_runs = native_runs_for_page(page)
        gray = gray_for_page(page)
        candidates = detect_title_block_candidates(gray, gray.shape[1], gray.shape[0])
        assert len(candidates) == 2

        region_texts = []
        for region in candidates:
            runs = native_text_runs_in_region(native_runs, region)
            region_texts.append(' '.join(r.text for r in runs))

        # Exactly one of the two regions contains the real drawing number,
        # and it must NOT be mixed with the revision-history table's own
        # text ("Reason For Issue" etc.) -- the real production bug this
        # proves fixed.
        matches = [t for t in region_texts if 'M19-M4C-C0-PW-AX-SD-05731' in t]
        assert len(matches) == 1
        assert 'Reason For Issue' not in matches[0]
        assert 'Rev:' in matches[0] and 'B' in matches[0]

    def test_native_bottom_strip_different_layout_still_recovers_all_fields_in_one_region(self):
        pdf, page = load_fixture_page('native_bottom_strip.pdf')
        native_runs = native_runs_for_page(page)
        gray = gray_for_page(page)
        candidates = detect_title_block_candidates(gray, gray.shape[1], gray.shape[0])
        assert len(candidates) >= 1
        runs = native_text_runs_in_region(native_runs, candidates[0])
        combined = ' '.join(r.text for r in runs)
        assert 'S-2.03' in combined
        assert 'ROOF PLAN' in combined

    def test_scanned_page_with_no_native_text_falls_back_to_targeted_ocr_on_the_region(self):
        pdf, page = load_fixture_page('scanned_no_native_text.pdf')
        native_runs = native_runs_for_page(page)
        assert native_runs == []  # confirms this fixture genuinely has no text layer
        gray = gray_for_page(page)
        candidates = detect_title_block_candidates(gray, gray.shape[1], gray.shape[0])
        assert len(candidates) >= 1

        found_label = False
        found_number_shaped_value = False
        for region in candidates:
            runs = native_text_runs_in_region(native_runs, region) or ocr_region(gray, region)
            assert all(r.method == 'ocr' for r in runs)  # no native text anywhere on this page
            texts = [r.text for r in runs]
            if 'Drawing' in texts and 'No:' in texts:
                found_label = True
            for r in texts:
                # A real, confirmed Tesseract artifact on this exact
                # fixture: it reads the drawing number's "SD" segment as
                # "5D" (a well-known S/5 character confusion), reported at
                # a visibly lower confidence (~18) than its clean
                # neighbors (~94-95) -- the same "low confidence flags a
                # bad recognition" signal Phase 2 already documented for
                # a different artifact (two tokens fusing into one). This
                # is accepted as a genuine, disclosed OCR-engine
                # limitation, not something this module's region-scoping
                # can or should paper over -- so this only asserts that
                # SOME drawing-number-SHAPED value was recovered, not an
                # exact character match.
                if r.startswith('M19-M4C-C0-PW-AX-') and 'D-0573' in r:
                    found_number_shaped_value = True
        assert found_label
        assert found_number_shaped_value

    def test_rotated_page_reports_the_pdfs_own_declared_rotation_exactly(self):
        pdf, page = load_fixture_page('rotated_90.pdf')
        assert page.get_rotation() == 90
        # The page's own reported size is unaffected by the declared
        # rotation -- every run's (left, top) stays in one consistent,
        # unrotated coordinate space; this service never rotates anything
        # itself (see drawing_vision.py's own module docstring).
        native_runs = native_runs_for_page(page)
        assert any('M19-M4C-C0-PW-AX-SD-05733' in r.text for r in native_runs)
