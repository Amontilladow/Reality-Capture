"""
Site Drawing Hub Drawing Intelligence Engine replacement: this is the
FIRST real pytest suite apps/ai-service has ever had (confirmed before
this change: no conftest.py, no test_*.py anywhere). Justified now
because, unlike the old ocr.py (a thin passthrough of Tesseract's own
already-computed output, kept untested on purpose with the interpretive
logic living in TypeScript instead), this module's grid-detection and
region-assignment logic is itself the thing that decides correctness --
there is no TypeScript-side equivalent to lean on, so it needs its own
real coverage.

Unit tests use synthetic numpy arrays (no PDF needed) for the pure pixel
logic. Integration tests use the real PDF fixtures in tests/fixtures/
(generated by generate_fixtures.py, committed as small static files) run
through pypdfium2 + the real OpenCV/pytesseract pipeline -- not mocked,
the same "confirmed by hand against the real engine" discipline this
whole engagement has used throughout.

Real incident added after this suite first shipped: rendering a WHOLE
page at a fixed 300 DPI OOM'd this service's 512MB container on a real
uploaded A0/A1-class engineering drawing within seconds. The two-tier
rendering fix (grid_detection_scale/rescale_region/region_crop_margins_pt)
has its own dedicated coverage below, including an end-to-end test
against a real full-size A0 PDF fixture (large_a0_sheet.pdf) proving the
array used for grid detection stays bounded regardless of the real
sheet's size.
"""
