"""Generates docs/COMPLIANCE_MATRIX.md from the rule manifest (single source of truth)."""
from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

from m4adm.rules import Manifest

ROOT = Path(__file__).resolve().parents[2]
MATRIX_FILES = {
    "sdd_planning": "docs/COMPLIANCE_MATRIX.md",
    "bdms_building": "docs/COMPLIANCE_MATRIX_BDMS.md",
}


def rule_test_index(tests_dir: Path) -> dict[str, list[str]]:
    """Rule id -> test files that assert on that id (by literal reference)."""
    idx: dict[str, list[str]] = defaultdict(list)
    if not tests_dir.exists():
        return idx
    pat = re.compile(r"\b((?:ADM|ENG|USR|PND|M4|DRM)-[A-Z0-9]+-[A-Z0-9]+)\b")
    for f in sorted(tests_dir.glob("test_*.py")):
        for rid in sorted(set(pat.findall(f.read_text(encoding="utf-8")))):
            idx[rid].append(f.name)
    return idx


def render_matrix(manifest: Manifest, tests_dir: Path | None = None) -> str:
    tests = rule_test_index(tests_dir or ROOT / "tests")
    s = manifest.spec
    out = [
        f"# Compliance matrix - profile `{manifest.profile}`",
        "",
        "> GENERATED by `m4adm matrix` from `rules/" + (manifest.path.name if manifest.path else "?")
        + "`. Do not edit by hand; edit the manifest and regenerate.",
        "",
        f"Specification: **{s['title']}**, version **{s['version']}** ({s['issuer']}), "
        f"file `{s['source_pdf']}` (SHA-256 `{s['source_pdf_sha256']}`, {s['source_pdf_pages']} pages). "
        "Page numbers are the printed page numbers, which equal the PDF page index.",
        "",
        "Evidence classes: `VERIFIED_SPEC` explicit in the PDF; `ENGINEERING_CHECK` M4 preliminary check, not "
        "claimed as an ADM rule; `PENDING_OFFICIAL_CONFIRMATION` needs the official template, QC tool, sample or ADM "
        "clarification; `USER_DECISION_REQUIRED` cannot be decided from geometry alone.",
        "",
        "*Tests* lists the test files that assert on the rule id. *Implementation*: IMPLEMENTED, PARTIAL "
        "(limitation stated), INTERFACE_ONLY (integration point without the official file), NOT_IMPLEMENTED.",
        "",
    ]
    counts = defaultdict(int)
    for r in manifest.rules:
        counts[r.evidence.value] += 1
    out += ["| Evidence class | Rules |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(counts.items())] + [""]
    out += ["## Rules", "",
            "| ID | Requirement | Official QC error | Evidence | Reference | Severity | Implementation | Tests | Known limitations |",
            "|---|---|---|---|---|---|---|---|---|"]
    aliased_from: dict[str, list[str]] = defaultdict(list)
    for src, dst in manifest.rule_aliases.items():
        if dst:
            aliased_from[dst].append(src)
    for r in manifest.rules:
        ref = r.ref.text() if r.ref else "-"
        tested = sorted({t for rid in [r.id, *aliased_from[r.id]] for t in tests.get(rid, [])})
        out.append(f"| {r.id} | {_esc(r.title)} | {_esc(r.qc_error or '-')} | {r.evidence.value} | {ref} | "
                   f"{r.severity.value} | {r.implementation} | {', '.join(tested) or '**none**'} | "
                   f"{_esc(r.limitation or '')} |")
    if manifest.rule_aliases:
        out += ["", "## Generic checks and how this profile maps them", "",
                "| Generic check | This profile's rule |", "|---|---|"]
        out += [f"| {src} | {dst or '*not applicable*'} |" for src, dst in sorted(manifest.rule_aliases.items())]
    out += ["", "## Layer tables", ""]
    for cat, spec in manifest.categories.items():
        out += [f"### {spec.label} - {spec.ref.text()}", "",
                "| Layer | Topology | Constraint | Colour | Linetype | Lineweight | Detail / parent | Block | PDF spelling variants |",
                "|---|---|---|---|---|---|---|---|---|"]
        for l in spec.layers:
            rel = l.detail or (f"parent: {l.parent}" if l.parent else "-")
            lw = "Default (0.25)" if l.lineweight == "default" else f"{int(l.lineweight) / 100:.2f}"
            if l.lineweight_accept:
                lw += " or " + ", ".join(f"{v / 100:.2f}" for v in l.lineweight_accept)
            out.append(f"| {l.name} | {l.topology} | {l.constraint} | {l.color} | {l.linetype} | {lw} | {rel} | "
                       f"{l.block or '-'} | {', '.join(l.aliases) or '-'} |")
        out.append("")
    out += ["## Attribute blocks (Section 6)", "", "| Block | PDF reference | Attributes (* mandatory, [domain]) |",
            "|---|---|---|"]
    for name, b in manifest.blocks.items():
        atts = ", ".join(f"{a.tag}{'*' if a.mandatory else ''} ({a.type}{', ' + a.domain if a.domain else ''})"
                         for a in b.attributes)
        out.append(f"| {name} | {b.ref.text()} | {atts} |")
    out += ["", "## Unresolved requirements", "",
            "Rules not fully verifiable today (evidence PENDING_OFFICIAL_CONFIRMATION, implementation PARTIAL / "
            "INTERFACE_ONLY / NOT_IMPLEMENTED):", ""]
    for r in manifest.rules:
        if r.evidence.value == "PENDING_OFFICIAL_CONFIRMATION" or r.implementation != "IMPLEMENTED":
            out.append(f"- **{r.id}** {_esc(r.title)} - {r.implementation}. {_esc(r.limitation or '')}")
    out.append("")
    return "\n".join(out)


def _esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")
