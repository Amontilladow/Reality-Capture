"""Extract Appendix 2 (plot category / usage type domain) from the ADM SDD PDF.

Usage:
    python scripts/extract_plot_usage.py <path/to/SDDPlanningDataSubmissionSpecifications_v1182.pdf> rules/adm_v1.18.2_plot_usage.yaml

Requires the `pdftotext` binary (poppler-utils). The output YAML is committed so
the tool does not need the PDF at runtime; re-run this script whenever a new
specification version is issued and review the diff by hand.
"""
from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

import yaml

CATEGORIES = {
    "agricultural", "archaeological", "commercial", "communication", "cultural",
    "diplomatic", "educational", "governmental", "health", "industrial", "private",
    "recreational", "religious", "residential", "transportation", "utility",
    "undefined", "investment", "public", "services", "Temporary", "publicBuilding",
    "publicOpenSpace",
}
PAGE_FOOTER = re.compile(r"SDD Planning Data Delivery Standards\s+(\d+)\s*$")


def main(pdf: Path, out: Path) -> None:
    text = subprocess.run(
        ["pdftotext", "-layout", str(pdf), "-"], check=True, capture_output=True, text=True
    ).stdout
    start = text.index("APPENDIX 2: DOMAIN VALUES FOR PLOT CATEGORY AND USAGE TYPE")
    page = None
    entries: list[dict] = []
    # Footer page numbers come after the rows of that page, so collect rows per page.
    pending: list[tuple[str, str]] = []
    for line in text[start:].splitlines():
        m = PAGE_FOOTER.search(line)
        if m:
            page = int(m.group(1))
            for cat, use in pending:
                entries.append({"category": cat, "usage": use, "page": page})
            pending = []
            continue
        parts = re.split(r"\s{2,}", line.strip(), maxsplit=1)
        if len(parts) == 2 and parts[0] in CATEGORIES:
            pending.append((parts[0], parts[1].rstrip()))
    if pending:
        raise SystemExit("rows found after the last page footer; check extraction")

    domain: dict[str, list[str]] = {}
    for e in entries:
        domain.setdefault(e["category"], []).append(e["usage"])
    doc = {
        "source_pdf_sha256": hashlib.sha256(pdf.read_bytes()).hexdigest(),
        "section": "Appendix 2: Domain values for plot category and usage type",
        "pages": f"{entries[0]['page']}-{entries[-1]['page']}",
        "as_of": "10/Nov/2019 (as stated in the PDF)",
        "evidence": "VERIFIED_SPEC",
        "note": (
            "Extracted verbatim (case-sensitive) by scripts/extract_plot_usage.py. "
            "The PDF notes that a proposed category/usage may be missing from this list; "
            "in that case ADM SDD must be consulted."
        ),
        "row_count": len(entries),
        "usage_by_category": domain,
    }
    out.write_text(
        "# GENERATED by scripts/extract_plot_usage.py from the ADM SDD PDF. Do not edit by hand.\n"
        + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=1000),
        encoding="utf-8",
    )
    print(f"{len(entries)} rows, {len(domain)} categories -> {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
