"""Extract DRM BDMS 4.1 code lists into rules/drm_bdms_v4.1_codelists.yaml.

Sources (official attachments to the BDMS 4.1 specification):
  * UPC_Land Use Classification.xls  (Appendix C)  - all Level 1..6 terms of the LandUse sheet
  * DRM_CPDQC_V2.3_UserManual.pdf    (Appendix 1)  - text-extractable part of the UnitUsageType list

Usage:
    python scripts/extract_drm_codelists.py <UPC xls> <QC manual pdf> rules/drm_bdms_v4.1_codelists.yaml

Needs `xlrd` (pip install xlrd==2.0.1) and the `pdftotext` binary. Several manual pages that hold
the UnitUsageType list are images; the union of both sources is therefore marked
PENDING_OFFICIAL_CONFIRMATION and checked as a WARNING, never as an ERROR.
"""
from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

import xlrd
import yaml


def upc_terms(xls: Path) -> dict[str, list[str]]:
    sheet = xlrd.open_workbook(str(xls)).sheet_by_name("LandUse")
    header_row = next(r for r in range(sheet.nrows) if str(sheet.cell_value(r, 2)).strip() == "Level 1")
    levels: dict[str, list[str]] = {f"level_{i}": [] for i in range(1, 7)}
    for r in range(header_row + 1, sheet.nrows):
        for i in range(1, 7):
            value = str(sheet.cell_value(r, 1 + i)).strip()
            if "still being defined" in value.lower():  # spreadsheet legend, not a term
                continue
            if value and value not in levels[f"level_{i}"]:
                levels[f"level_{i}"].append(value)
    return levels


def manual_unit_usage(pdf: Path) -> list[str]:
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True, capture_output=True,
                          text=True).stdout
    start = text.index("4.UnitDetail Attribute Block (UnitUsageType)")
    end = text.index("5.DrawingDetail Attribute Block")
    out: list[str] = []
    for line in text[start:end].splitlines():
        line = line.strip()
        if not line or line.startswith(("Page ", "BDMS", "Abu Dhabi", "Town Planning", "Spatial Data", "UnitUsageType",
                                        "4.UnitDetail")):
            continue
        if re.fullmatch(r"[\w .,&/()'-]+", line) and line not in out:
            out.append(line)
    return out


def main(xls: Path, pdf: Path, out: Path) -> None:
    levels = upc_terms(xls)
    manual = manual_unit_usage(pdf)
    upc_all = [t for i in range(1, 7) for t in levels[f"level_{i}"]]
    union = list(dict.fromkeys(upc_all + manual))
    doc = {
        "sources": {
            "upc_xls": {"file": xls.name, "sha256": hashlib.sha256(xls.read_bytes()).hexdigest()},
            "qc_manual": {"file": pdf.name, "sha256": hashlib.sha256(pdf.read_bytes()).hexdigest()},
        },
        "evidence": "PENDING_OFFICIAL_CONFIRMATION",
        "note": "UnitUsageType list = union of all UPC LandUse terms (Levels 1-6) and the text-extractable part of "
                "the QC manual Appendix 1 list (some manual pages are images). Checked as WARNING only.",
        "upc_levels": levels,
        "qc_manual_unit_usage_text": manual,
        "unit_usage_type": union,
    }
    out.write_text("# GENERATED by scripts/extract_drm_codelists.py. Do not edit by hand.\n"
                   + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=1000), encoding="utf-8")
    print(f"UPC terms {len(upc_all)}, manual text terms {len(manual)}, union {len(union)} -> {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))
